package io.github.vaquarkhan.springailaya.benchmark;

import java.util.List;
import java.util.Map;

/**
 * Renders the benchmark report as Markdown. Numbers only; interpretation belongs in the
 * proposal, where it can cite these tables.
 */
final class Report {

	private Report() {
	}

	@SuppressWarnings("unchecked")
	static String markdown(Map<String, Object> r) {
		StringBuilder md = new StringBuilder();
		md.append("# Laya backend benchmark results\n\n");
		md.append("Generated by `LayaBenchmark` on ").append(r.get("date")).append(".\n\n");
		md.append("- Laya: ").append(r.get("laya")).append('\n');
		md.append("- Host: ").append(r.get("host")).append('\n');
		md.append("- Jev: ").append(r.get("jev")).append("\n\n");

		md.append("## 1. Accuracy and calibration (zero-shot, one choice question)\n\n");
		md.append("| Dataset | Options | Backend | Examples | Accuracy | ECE answer_confidence | ECE Jev formula | ECE entropy | ms/example (batched) |\n");
		md.append("|---|---|---|---|---|---|---|---|---|\n");
		Map<String, Object> accuracy = (Map<String, Object>) r.get("accuracy");
		accuracy.forEach((name, value) -> {
			Map<String, Object> entry = (Map<String, Object>) value;
			for (String backend : List.of("laya", "jev")) {
				Map<String, Object> s = (Map<String, Object>) entry.get(backend);
				if (s == null) {
					continue;
				}
				md.append("| ").append(name).append(" | ").append(entry.get("options")).append(" | ").append(backend)
					.append(" | ").append(s.get("answered")).append(" | ").append(s.get("accuracy")).append(" | ")
					.append(s.get("ece_answer_confidence")).append(" | ").append(s.get("ece_jev_formula")).append(" | ")
					.append(s.get("ece_entropy")).append(" | ").append(s.get("ms_per_example")).append(" |\n");
			}
		});

		md.append("\nComparison mode: ").append(r.getOrDefault("comparison_mode", "not recorded")).append("\n\n");
		md.append("### Input receipts\n\n");
		md.append("SHA-256 of the ordered state and expected labels, and of the exact question payload. A paired run with Jev must show the same hashes.\n\n");
		md.append("| Dataset | Examples | Options | state+label SHA-256 | question SHA-256 |\n|---|---|---|---|---|\n");
		accuracy.forEach((name, value) -> {
			Map<String, Object> receipt = (Map<String, Object>) ((Map<String, Object>) value).get("parity_receipt");
			if (receipt == null) {
				md.append("| ").append(name).append(" | n/a | n/a | not recorded | not recorded |\n");
				return;
			}
			md.append("| ").append(name).append(" | ").append(receipt.get("examples")).append(" | ")
				.append(receipt.get("option_count")).append(" | `").append(receipt.get("state_label_sha256"))
				.append("` | `").append(receipt.get("question_sha256")).append("` |\n");
		});

		md.append("\n## 2. Serving only confident answers (Laya, answer_confidence floor)\n\n");
		md.append("Share of requests Laya would serve at each floor, and its accuracy on that share. The rest would escalate.\n\n");
		md.append("| Dataset | Floor | Served by Laya | Accuracy when served |\n|---|---|---|---|\n");
		accuracy.forEach((name, value) -> {
			Map<String, Object> laya = (Map<String, Object>) ((Map<String, Object>) value).get("laya");
			for (Map<String, Object> row : (List<Map<String, Object>>) laya.get("selective")) {
				md.append("| ").append(name).append(" | ").append(row.get("min_answer_confidence")).append(" | ")
					.append(row.get("served_share")).append(" | ").append(row.get("accuracy_when_served")).append(" |\n");
			}
		});

		md.append("\n## 3. JevConfidenceGate (floor 0.6) on Laya answers\n\n");
		md.append("Native = Laya's `confidence` (what a plain TypeSafeClient passes on). Jev formula = what LayaTypeSafeClient passes on.\n\n");
		md.append("| Dataset | Escalated, native | Escalated, Jev formula | Decisions that differ | Accuracy of the differing answers |\n|---|---|---|---|---|\n");
		accuracy.forEach((name, value) -> {
			Map<String, Object> laya = (Map<String, Object>) ((Map<String, Object>) value).get("laya");
			Map<String, Object> g = (Map<String, Object>) laya.get("gate_floor_0_6");
			md.append("| ").append(name).append(" | ").append(g.get("escalated_with_native_confidence")).append(" | ")
				.append(g.get("escalated_with_jev_formula")).append(" | ").append(g.get("decisions_that_differ"))
				.append(" | ").append(g.get("accuracy_of_differing")).append(" |\n");
		});

		md.append("\n## 4. Single-request latency (SST-2, one question)\n\n");
		md.append("```\n").append(r.get("latency")).append("\n```\n");

		md.append("\n## 5. systemOneAll: upstream fan-out vs Laya batch endpoint\n\n");
		md.append("```\n").append(r.get("systemOneAll")).append("\n```\n");

		md.append("\n## 6. JevDocumentFilter end to end (4 questions per passage)\n\n");
		Map<String, Object> rag = (Map<String, Object>) r.get("ragFilter");
		md.append("| Client | Passages | Wall ms per run (interleaved) |\n|---|---|---|\n");
		md.append("| plain TypeSafeClient pointed at Laya | ").append(rag.get("passages")).append(" | ")
			.append(rag.get("plain_typesafe_client_ms_runs")).append(" |\n");
		md.append("| LayaTypeSafeClient | ").append(rag.get("passages")).append(" | ")
			.append(rag.get("laya_adapter_ms_runs")).append(" |\n\n");
		md.append("Speedup, best run of each: ").append(rag.get("speedup_best_of_runs")).append("x\n\n");
		md.append("Kept by the plain client:\n\n");
		((List<String>) rag.get("kept_plain")).forEach(k -> md.append("- ").append(k).append('\n'));
		md.append("\nKept via the adapter:\n\n");
		((List<String>) rag.get("kept_adapter")).forEach(k -> md.append("- ").append(k).append('\n'));
		return md.toString();
	}

}
